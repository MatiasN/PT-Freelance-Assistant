from dataclasses import dataclass, field
from datetime import date
from enum import StrEnum

from app.config import VatRegime
from app.fiscal.social_security import declaration_deadline


class DeadlineKind(StrEnum):
    SOCIAL_SECURITY_DECLARATION = "social_security_declaration"
    SOCIAL_SECURITY_PAYMENT = "social_security_payment"
    VAT_DECLARATION = "vat_declaration"
    VAT_PAYMENT = "vat_payment"
    EFATURA = "efatura"
    IRS_FILING = "irs_filing"
    IRS_PAYMENT = "irs_payment"
    VIACTT = "viactt"


@dataclass(frozen=True)
class OfficialLink:
    title: str
    url: str


@dataclass(frozen=True)
class Deadline:
    key: str
    kind: DeadlineKind
    title: str
    due: date
    guide_markdown: str
    links: tuple[OfficialLink, ...] = ()
    repeat_every_days: int | None = None
    repeat_until: date | None = None
    reminder_days_before: tuple[int, ...] = field(default=(7, 1))

    def description_markdown(self) -> str:
        lines = [self.guide_markdown.strip(), "", "**Official links**"]
        lines += [f"- [{link.title}]({link.url})" for link in self.links]
        lines += [
            "",
            "_Generated by PT Tax Assistant — an organisational ledger. It never accesses "
            "Portal das Finanças or Segurança Social Direta on your behalf._",
        ]
        return "\n".join(lines)


SEGURANCA_SOCIAL_DIRETA = OfficialLink("Segurança Social Direta", "https://app.seg-social.pt")
SS_INDEPENDENT_WORKERS = OfficialLink(
    "Guia prático — Trabalhadores independentes",
    "https://www.seg-social.pt/trabalhadores-independentes",
)
PORTAL_FINANCAS = OfficialLink("Portal das Finanças", "https://www.portaldasfinancas.gov.pt")
IRS_PORTAL = OfficialLink("IRS — Entregar declaração", "https://irs.portaldasfinancas.gov.pt")
EFATURA = OfficialLink("e-Fatura", "https://faturas.portaldasfinancas.gov.pt")
VIACTT = OfficialLink("ViaCTT", "https://www.viactt.pt")

QUARTER_NAMES = {1: "1.º trimestre", 2: "2.º trimestre", 3: "3.º trimestre", 4: "4.º trimestre"}


def _social_security_declarations(year: int) -> list[Deadline]:
    deadlines = []
    for declared_year, quarter in [(year - 1, 4), (year, 1), (year, 2), (year, 3)]:
        due = declaration_deadline(declared_year, quarter)
        deadlines.append(
            Deadline(
                key=f"ss-declaration-{declared_year}-q{quarter}",
                kind=DeadlineKind.SOCIAL_SECURITY_DECLARATION,
                title=f"Segurança Social: declaração trimestral ({QUARTER_NAMES[quarter]} "
                f"{declared_year})",
                due=due,
                guide_markdown=f"""
## Declaração trimestral — {QUARTER_NAMES[quarter]} {declared_year}

1. Open the **PT Tax Assistant → Estimator** and note the services income for the quarter.
2. Log in to **Segurança Social Direta** → *Emprego* → *Declaração Trimestral*.
3. Confirm/enter the gross amount of services provided (*prestação de serviços*) in each
   month of the quarter. Income is reported by the date the service was invoiced.
4. Submit and download the proof (*comprovativo*).
5. The resulting contribution is charged for the next three months, payable between the
   10th and the 20th of each following month.
""",
                links=(SEGURANCA_SOCIAL_DIRETA, SS_INDEPENDENT_WORKERS),
            )
        )
    return deadlines


def _social_security_payments(year: int) -> list[Deadline]:
    return [
        Deadline(
            key=f"ss-payment-{year}-{month:02d}",
            kind=DeadlineKind.SOCIAL_SECURITY_PAYMENT,
            title="Segurança Social: pagamento de contribuições (até dia 20)",
            due=date(year, month, 20),
            guide_markdown="""
## Pagamento mensal de contribuições

Only applies if the last quarterly declaration produced a contribution above zero.

1. Segurança Social Direta → *Conta-Corrente* → *Pagamentos* → generate the payment reference.
2. Pay by Multibanco / homebanking between the 10th and the 20th.
3. Consider enabling *Débito Direto* to avoid missing this deadline.
""",
            links=(SEGURANCA_SOCIAL_DIRETA,),
            reminder_days_before=(3,),
        )
        for month in range(1, 13)
    ]


def _vat_deadlines(year: int) -> list[Deadline]:
    deadlines = []
    for declared_year, quarter, month in [
        (year - 1, 4, 2),
        (year, 1, 5),
        (year, 2, 8),
        (year, 3, 11),
    ]:
        period = f"{QUARTER_NAMES[quarter]} {declared_year}"
        deadlines.append(
            Deadline(
                key=f"vat-declaration-{declared_year}-q{quarter}",
                kind=DeadlineKind.VAT_DECLARATION,
                title=f"IVA: declaração periódica trimestral ({period})",
                due=date(year, month, 20),
                guide_markdown=f"""
## Declaração Periódica de IVA — {period}

1. Portal das Finanças → *IVA* → *Entregar Declaração Periódica*.
2. Services to non-EU business clients are not taxable in Portugal: report the quarter's
   total in the *Quadro 06* field for operations located outside Portugal (confirm the
   exact field with your accountant).
3. Submit even when no VAT is due, and keep the comprovativo.
""",
                links=(PORTAL_FINANCAS,),
            )
        )
        deadlines.append(
            Deadline(
                key=f"vat-payment-{declared_year}-q{quarter}",
                kind=DeadlineKind.VAT_PAYMENT,
                title=f"IVA: pagamento ({period})",
                due=date(year, month, 25),
                guide_markdown="""
## Pagamento de IVA

Only if the periodic declaration produced VAT payable. Use the payment reference shown
after submitting the declaration (Portal das Finanças → *Pagamentos*).
""",
                links=(PORTAL_FINANCAS,),
                reminder_days_before=(3,),
            )
        )
    return deadlines


def _irs_deadlines(year: int) -> list[Deadline]:
    income_year = year - 1
    return [
        Deadline(
            key=f"efatura-household-{year}",
            kind=DeadlineKind.EFATURA,
            title="e-Fatura: confirmar agregado familiar (até 15 fev)",
            due=date(year, 2, 15),
            guide_markdown="""
## Agregado familiar

Portal das Finanças → *Dados Pessoais* → *Agregado Familiar*. Confirm the household as of
31 December of the previous year.
""",
            links=(PORTAL_FINANCAS,),
        ),
        Deadline(
            key=f"efatura-validation-{year}",
            kind=DeadlineKind.EFATURA,
            title="e-Fatura: validar faturas e despesas da atividade (até 25 fev)",
            due=date(year, 2, 25),
            guide_markdown="""
## Validar faturas no e-Fatura

1. e-Fatura → *Complementar Informação Atividade Profissional*: mark which purchases are
   activity expenses (relevant for the 15% expense rule of the simplified regime).
2. *Complementar Informação Despesas Dedutíveis*: classify pending personal expenses.
""",
            links=(EFATURA,),
        ),
        Deadline(
            key=f"irs-filing-opens-{year}",
            kind=DeadlineKind.IRS_FILING,
            title=f"IRS {income_year}: abre a entrega do Modelo 3",
            due=date(year, 4, 1),
            guide_markdown=f"""
## Entrega da declaração de IRS {income_year} (1 abril — 30 junho)

1. Use the **PT Tax Assistant → Estimator** for the year {income_year} as a sanity check.
2. Modelo 3 must include **Anexo A** (employment) and **Anexo B** (simplified regime,
   activity code from the art. 151.º table, e.g. 1519).
3. Compare the AT simulation with the estimate before submitting.
""",
            links=(IRS_PORTAL,),
            reminder_days_before=(1,),
        ),
        Deadline(
            key=f"irs-filing-closes-{year}",
            kind=DeadlineKind.IRS_FILING,
            title=f"IRS {income_year}: último dia de entrega do Modelo 3",
            due=date(year, 6, 30),
            guide_markdown=f"""
## Prazo final — IRS {income_year}

Late filing carries a fine (*coima*). Submit through the IRS portal and keep the
comprovativo de entrega and the liquidação once issued.
""",
            links=(IRS_PORTAL,),
            reminder_days_before=(14, 3),
        ),
        Deadline(
            key=f"irs-payment-{year}",
            kind=DeadlineKind.IRS_PAYMENT,
            title=f"IRS {income_year}: data limite de pagamento",
            due=date(year, 8, 31),
            guide_markdown="""
## Pagamento do IRS

If the liquidação shows tax payable, pay using the reference in the *nota de cobrança*
(Portal das Finanças → *Pagamentos* → *Consultar Documentos de Cobrança*). Use the IRS
savings pool tracked in PT Tax Assistant.
""",
            links=(PORTAL_FINANCAS,),
        ),
    ]


def _viactt_reminder(year: int, interval_days: int) -> Deadline:
    return Deadline(
        key=f"viactt-{year}",
        kind=DeadlineKind.VIACTT,
        title="ViaCTT: verificar caixa postal eletrónica",
        due=date(year, 1, 1),
        guide_markdown="""
## Verificar a ViaCTT

Notifications from AT and Segurança Social delivered to the ViaCTT mailbox are presumed
received after 25 days even if never opened, so deadlines may already be running.

1. Log in to ViaCTT and open every new message.
2. Download notifications and record any new deadline in this calendar.
""",
        links=(VIACTT,),
        repeat_every_days=interval_days,
        repeat_until=date(year, 12, 31),
        reminder_days_before=(0,),
    )


def fiscal_deadlines(
    year: int, *, vat_regime: VatRegime, viactt_interval_days: int
) -> list[Deadline]:
    deadlines = _social_security_declarations(year) + _social_security_payments(year)
    if vat_regime == VatRegime.QUARTERLY:
        deadlines += _vat_deadlines(year)
    deadlines += _irs_deadlines(year)
    deadlines.append(_viactt_reminder(year, viactt_interval_days))
    return sorted(deadlines, key=lambda deadline: (deadline.due, deadline.key))
